//! Memory (DESIGN §4.6). `<home>/memory/` is a git repo of plain files. rpi loads
//! `<home>/AGENTS.md` as project context (upstream `context_files.rs`), and that file is
//! regenerated from `USER.md` and `MEMORY.md` before every child starts.

use anyhow::{bail, Context};
use std::path::{Path, PathBuf};
use std::process::Command;

const USER: &str = "USER.md";
const MEMORY: &str = "MEMORY.md";
/// Subject prefix of every commit this module makes. `/memory undo` looks for it.
const PREFIX: &str = "memory: ";

/// Serialises git work in the memory repo. The router and the job scheduler both commit to it.
static GIT: std::sync::Mutex<()> = std::sync::Mutex::new(());

fn lock() -> std::sync::MutexGuard<'static, ()> {
    GIT.lock().unwrap_or_else(|e| e.into_inner())
}

pub fn dir(home: &Path) -> PathBuf {
    home.join("memory")
}

/// Idempotent. Creates the files and the repo on first use, regenerates `<home>/AGENTS.md`,
/// and commits whatever changed (the seed files, on first start).
pub fn prepare(home: &Path) -> anyhow::Result<()> {
    let _guard = lock();
    let _fs = crate::agent::fs();
    let dir = dir(home);
    std::fs::create_dir_all(dir.join("notes"))?;
    for name in [USER, MEMORY] {
        let path = dir.join(name);
        if !path.exists() {
            std::fs::write(&path, format!("# {name}\n"))?;
        }
    }
    if !dir.join(".git").exists() {
        git(&dir, &["init", "-q"])?;
    }
    // Local to this repo only: never the account's global identity.
    git(&dir, &["config", "user.name", "Zephyr"])?;
    git(&dir, &["config", "user.email", "zephyr@localhost"])?;

    let agents = format!(
        "<!-- Generated by zephyr from memory/{USER} and memory/{MEMORY}. Edit those files instead. -->\n\n{}\n\n{}",
        std::fs::read_to_string(dir.join(USER))?,
        std::fs::read_to_string(dir.join(MEMORY))?,
    );
    std::fs::write(home.join("AGENTS.md"), agents)?;
    commit_locked(home)?;
    Ok(())
}

/// Commits every change in the memory dir as `memory: <utc time>`. Returns false when clean.
pub fn commit_if_changed(home: &Path) -> anyhow::Result<bool> {
    let _guard = lock();
    let _fs = crate::agent::fs();
    commit_locked(home)
}

fn commit_locked(home: &Path) -> anyhow::Result<bool> {
    let dir = dir(home);
    if git(&dir, &["status", "--porcelain"])?.is_empty() {
        return Ok(false);
    }
    git(&dir, &["add", "-A"])?;
    let now = (crate::unix_millis() / 1000) as u64;
    git(
        &dir,
        &["commit", "-q", "-m", &format!("{PREFIX}{}", iso_utc(now))],
    )?;
    Ok(true)
}

/// The owner's `/memory` commands. `None` for any other text. The reply is always text.
pub fn command(home: &Path, text: &str) -> Option<String> {
    let _guard = lock();
    let _fs = crate::agent::fs();
    let text = text.trim();
    if text != "/memory" && !text.starts_with("/memory ") {
        return None;
    }
    let reply = match text {
        "/memory log" => git(&dir(home), &["log", "-n", "10", "--format=%h %s"]),
        "/memory undo" => undo(home),
        _ => Ok("usage: /memory log | /memory undo".into()),
    };
    Some(match reply {
        Ok(out) => out,
        Err(e) => format!("[zephyr] memory: {e:#}"),
    })
}

/// `git revert`s the newest memory commit that has not been undone yet.
fn undo(home: &Path) -> anyhow::Result<String> {
    let dir = dir(home);
    if !git(&dir, &["status", "--porcelain"])?.is_empty() {
        bail!("there are uncommitted changes; try again after the run settles");
    }
    // Newest first. Each revert cancels the next memory commit below it, so repeated undos walk back.
    let log = git(&dir, &["log", "--format=%H %s"])?;
    let mut owed = 0;
    let Some(sha) = log.lines().find_map(|line| {
        let (sha, subject) = line.split_once(' ')?;
        if subject.starts_with("Revert \"memory: ") {
            owed += 1;
            None
        } else if subject.starts_with(PREFIX) && owed > 0 {
            owed -= 1;
            None
        } else {
            subject.starts_with(PREFIX).then_some(sha)
        }
    }) else {
        bail!("no memory commit to undo");
    };
    // The seed commit holds the first files; reverting it would delete them.
    if git(&dir, &["rev-list", "--max-parents=0", "HEAD"])?
        .lines()
        .any(|root| root == sha)
    {
        bail!("the first memory commit is the seed and is not undone");
    }
    if let Err(e) = git(&dir, &["revert", "--no-edit", sha]) {
        let _ = git(&dir, &["revert", "--abort"]); // leave the tree as it was
        return Err(e.context("the revert conflicted"));
    }
    let stat = git(&dir, &["show", "--stat", "--format=%h %s", "HEAD"])?;
    Ok(format!(
        "[zephyr] undid {}\n{stat}",
        sha.get(..7).unwrap_or(sha)
    ))
}

/// Whether rpi will load `<home>/AGENTS.md` for this home: `<agent_dir>/trust.json` must not
/// record `false` for it. `session.rs` skips context files for an untrusted cwd, and a missing
/// decision counts as trusted (`config.rs` `project_trust_decision`, `session.rs` `resolve_project_trust`).
pub fn context_trusted(home: &Path, agent_dir: &Path) -> anyhow::Result<bool> {
    let _fs = crate::agent::fs();
    let text = match std::fs::read_to_string(agent_dir.join("trust.json")) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(true),
        Err(e) => return Err(e.into()),
    };
    let store: std::collections::HashMap<String, Option<bool>> = serde_json::from_str(&text)?;
    let key = std::fs::canonicalize(home)
        .unwrap_or_else(|_| home.to_path_buf())
        .to_string_lossy()
        .into_owned();
    Ok(store.get(&key) != Some(&Some(false)))
}

fn git(dir: &Path, args: &[&str]) -> anyhow::Result<String> {
    let out = crate::agent::cmd(&mut Command::new("git"))
        .arg("-C")
        .arg(dir)
        .args(args)
        .output()
        .context("running git")?;
    if !out.status.success() {
        bail!(
            "git {}: {}",
            args[0],
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

/// `YYYY-MM-DDTHH:MM:SSZ` for a Unix time, without a date crate (Hinnant's civil_from_days).
fn iso_utc(secs: u64) -> String {
    let days = secs as i64 / 86_400;
    let rem = secs % 86_400;
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 + i64::from(month <= 2);
    format!(
        "{year:04}-{month:02}-{day:02}T{:02}:{:02}:{:02}Z",
        rem / 3600,
        rem % 3600 / 60,
        rem % 60
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A fresh home per call: `test_dir` names collide when tests run in the same millisecond.
    fn home() -> PathBuf {
        static N: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
        let n = N.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        crate::test_dir(&format!("memory-{n}"))
    }

    fn commits(home: &Path) -> Vec<String> {
        git(&dir(home), &["log", "--format=%s"])
            .unwrap()
            .lines()
            .map(String::from)
            .collect()
    }

    #[test]
    fn prepare_is_idempotent_and_keeps_edits() {
        let home = home();
        prepare(&home).unwrap();
        std::fs::write(dir(&home).join(MEMORY), "likes tea\n").unwrap();
        prepare(&home).unwrap();
        assert!(dir(&home).join("notes").is_dir());
        assert_eq!(
            std::fs::read_to_string(dir(&home).join(MEMORY)).unwrap(),
            "likes tea\n"
        );
        // The first prepare committed the seed files; the second had nothing to add.
        assert_eq!(commits(&home).len(), 2, "one seed commit, one edit commit");
    }

    #[test]
    fn commits_only_when_changed_with_zephyr_identity() {
        let home = home();
        prepare(&home).unwrap();
        assert!(!commit_if_changed(&home).unwrap());
        std::fs::write(dir(&home).join(USER), "name: Aiden\n").unwrap();
        assert!(commit_if_changed(&home).unwrap());
        let log = git(&dir(&home), &["log", "-1", "--format=%an <%ae>|%s"]).unwrap();
        let (who, subject) = log.split_once('|').unwrap();
        assert_eq!(who, "Zephyr <zephyr@localhost>");
        assert!(subject.starts_with("memory: 20"), "got {subject}");
        assert!(!commit_if_changed(&home).unwrap());
    }

    #[test]
    fn undo_reverts_the_newest_memory_commit_and_walks_back() {
        let home = home();
        prepare(&home).unwrap();
        std::fs::write(dir(&home).join(MEMORY), "one\n").unwrap();
        commit_if_changed(&home).unwrap();
        std::fs::write(dir(&home).join(MEMORY), "two\n").unwrap();
        commit_if_changed(&home).unwrap();

        let reply = command(&home, "/memory undo").unwrap();
        assert!(reply.starts_with("[zephyr] undid "), "got {reply}");
        assert!(reply.contains("MEMORY.md"), "reply names the file: {reply}");
        assert_eq!(
            std::fs::read_to_string(dir(&home).join(MEMORY)).unwrap(),
            "one\n"
        );

        command(&home, "/memory undo").unwrap();
        assert_eq!(
            std::fs::read_to_string(dir(&home).join(MEMORY)).unwrap(),
            "# MEMORY.md\n",
            "second undo skips the revert commit and reverts the one before"
        );
        // Undo is a revert, not a reset: history keeps every commit.
        assert_eq!(commits(&home).len(), 5);
    }

    #[test]
    fn undo_refuses_to_run_over_uncommitted_edits() {
        let home = home();
        prepare(&home).unwrap();
        std::fs::write(dir(&home).join(MEMORY), "pending\n").unwrap();
        let reply = command(&home, "/memory undo").unwrap();
        assert!(reply.contains("uncommitted"), "got {reply}");
        assert_eq!(
            std::fs::read_to_string(dir(&home).join(MEMORY)).unwrap(),
            "pending\n"
        );
    }

    #[test]
    fn log_shows_the_last_ten_commits() {
        let home = home();
        prepare(&home).unwrap();
        for i in 0..11 {
            std::fs::write(dir(&home).join(MEMORY), format!("{i}\n")).unwrap();
            commit_if_changed(&home).unwrap();
        }
        let reply = command(&home, "/memory log").unwrap();
        assert_eq!(reply.lines().count(), 10);
        assert!(reply.lines().all(|l| l.contains("memory: ")));
    }

    #[test]
    fn agents_md_carries_both_memory_files() {
        let home = home();
        prepare(&home).unwrap();
        std::fs::write(dir(&home).join(USER), "USER-FACT-7\n").unwrap();
        std::fs::write(dir(&home).join(MEMORY), "MEMORY-FACT-9\n").unwrap();
        prepare(&home).unwrap();
        let agents = std::fs::read_to_string(home.join("AGENTS.md")).unwrap();
        assert!(agents.contains("USER-FACT-7"));
        assert!(agents.contains("MEMORY-FACT-9"));
    }

    #[test]
    fn other_text_is_not_a_memory_command() {
        let home = home();
        assert!(command(&home, "hello /memory log").is_none());
        assert!(command(&home, "/memoryx").is_none());
        assert!(command(&home, "/memory").unwrap().starts_with("usage"));
    }

    #[test]
    fn undo_never_reverts_the_seed_commit() {
        let home = home();
        prepare(&home).unwrap();
        std::fs::write(dir(&home).join(MEMORY), "one\n").unwrap();
        commit_if_changed(&home).unwrap();
        command(&home, "/memory undo").unwrap(); // reverts "one"
        let reply = command(&home, "/memory undo").unwrap();
        assert!(reply.contains("seed"), "got {reply}");
        assert_eq!(
            commits(&home).len(),
            3,
            "nothing was reverted past the seed"
        );
        assert!(dir(&home).join(USER).exists());
    }

    #[test]
    fn a_trust_decision_of_false_is_the_only_denial() {
        let root = crate::test_dir("memory-trust");
        let home = root.join("home");
        let agent = root.join("agent");
        std::fs::create_dir_all(&home).unwrap();
        std::fs::create_dir_all(&agent).unwrap();
        assert!(context_trusted(&home, &agent).unwrap(), "no trust.json");
        let key = std::fs::canonicalize(&home)
            .unwrap()
            .to_string_lossy()
            .into_owned();
        std::fs::write(agent.join("trust.json"), format!(r#"{{"{key}": null}}"#)).unwrap();
        assert!(
            context_trusted(&home, &agent).unwrap(),
            "null is no decision"
        );
        std::fs::write(agent.join("trust.json"), format!(r#"{{"{key}": false}}"#)).unwrap();
        assert!(!context_trusted(&home, &agent).unwrap());
    }

    #[test]
    fn formats_utc_timestamps() {
        assert_eq!(iso_utc(0), "1970-01-01T00:00:00Z");
        assert_eq!(iso_utc(1_700_000_000), "2023-11-14T22:13:20Z");
        assert_eq!(iso_utc(951_782_400), "2000-02-29T00:00:00Z", "leap day");
    }
}
